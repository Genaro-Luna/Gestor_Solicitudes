package solicitudes;

public class Estudiante {

    public String legajo;
    public String nombre;
    public String apellido;
    public String email;

    public Estudiante(String legajo, String nombre, String apellido, String email) {
        this.legajo = legajo;
        this.nombre = nombre;
        this.apellido = apellido;
        this.email = email;
    }
}
